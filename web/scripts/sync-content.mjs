// Regenerates content/tracker-data.ts from the tracker. Run after every roadmap change
// until cut-over: `npm run content:sync`. A unit test fails if the two drift apart.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractContent, readTrackerHtml } from "./tracker-source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../content/tracker-data.ts");
const content = extractContent(readTrackerHtml());

const body = `// GENERATED by scripts/sync-content.mjs from tracker/fde-journey-tracker.html.
// Do not edit by hand: change the tracker, then run \`npm run content:sync\`.
import type { TrackerContent } from "./types";

export const trackerContent = ${JSON.stringify(content, null, 1)} satisfies TrackerContent;
`;
writeFileSync(out, body);
const count = (a) => a.length;
console.log(
  `content/tracker-data.ts written: ${count(content.phases)} phases, ${count(content.certs)} certifications, ` +
    `${count(content.projects)} projects, ${count(content.scaler)} Scaler modules, ` +
    `${Object.keys(content.resources).length} resource lists, ${count(content.papers)} papers, ${count(content.books)} books`,
);
